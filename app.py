import streamlit as st
import pandas as pd
import joblib
import os
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix

st.set_page_config(page_title="ML Classifier Evaluator", layout="wide")
st.title("Machine Learning Classification Evaluator")
st.markdown("Upload a test dataset and select a model to view its evaluation metrics.")

# Sidebar Configuration
st.sidebar.header("Configuration")
model_choice = st.sidebar.selectbox("Select a Pre-trained Model",
    ["Logistic Regression", "Decision Tree", "KNN", "Naive Bayes", "SVM"])

model_files = {
    "Logistic Regression": "model/logistic_regression.joblib",
    "Decision Tree": "model/decision_tree.joblib",
    "KNN": "model/knn.joblib",
    "Naive Bayes": "model/naive_bayes.joblib",
    "SVM": "model/svm.joblib"
}

# File Uploader
uploaded_file = st.file_uploader("Upload CSV Dataset (must contain 'target' column)", type=["csv"])

if uploaded_file is not None:
    df = pd.read_csv(uploaded_file)
    st.write("### Dataset Preview")
    st.dataframe(df.head())

    # if 'target' in df.columns:
    #     X = df.drop('target', axis=1)
    #     y_true = df['target']

    if 'Outcome' in df.columns:
        X = df.drop('Outcome', axis=1)
        y_true = df['Outcome']

        model_path = model_files[model_choice]
        if os.path.exists(model_path):
            model = joblib.load(model_path)

            y_pred = model.predict(X)
            y_prob = model.predict_proba(X)[:, 1] if hasattr(model, "predict_proba") else None

            acc = accuracy_score(y_true, y_pred)
            prec = precision_score(y_true, y_pred, zero_division=0)
            rec = recall_score(y_true, y_pred, zero_division=0)
            f1 = f1_score(y_true, y_pred, zero_division=0)
            mcc = matthews_corrcoef(y_true, y_pred)
            auc = roc_auc_score(y_true, y_prob) if y_prob is not None else "N/A"

            st.write(f"### Performance Metrics: {model_choice}")
            col1, col2, col3 = st.columns(3)
            col1.metric("Accuracy", f"{acc:.4f}")
            col1.metric("AUC", f"{auc:.4f}" if auc != "N/A" else auc)
            col2.metric("Precision", f"{prec:.4f}")
            col2.metric("Recall", f"{rec:.4f}")
            col3.metric("F1 Score", f"{f1:.4f}")
            col3.metric("MCC", f"{mcc:.4f}")

            st.write("### Confusion Matrix")
            cm = confusion_matrix(y_true, y_pred)
            fig, ax = plt.subplots(figsize=(4,3))
            sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax)
            ax.set_xlabel('Predicted')
            ax.set_ylabel('Actual')
            st.pyplot(fig)
        else:
            st.error("Model artifact not found. Please run 'train_models.py' first.")
    else:
        st.error("The uploaded CSV must contain a column named 'target'.")
else:
    st.info("Awaiting file upload. You can upload the 'test_data.csv' generated during training.")